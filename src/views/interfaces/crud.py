from abc import ABC, abstractmethod
from sqlalchemy.ext.asyncio import AsyncSession
from typing import List

class CRUDInferface(ABC):
    @abstractmethod
    async def list(self, session:AsyncSession) -> List:...
    @abstractmethod
    async def create(self, payload, session:AsyncSession):...
    @abstractmethod
    async def retrieve(self, id:int, session:AsyncSession):...
    @abstractmethod
    async def update(self, id:int, session:AsyncSession, payload):...
    @abstractmethod
    async def delete(self, id:int, session:AsyncSession, payload):...
